// Run with an existing Playwright installation: PLAYWRIGHT_MODULE=/absolute/package/index.mjs.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args:['--no-sandbox'], headless:true});
const base = 'http://127.0.0.1:4173';
await mkdir('research/screenshots',{recursive:true});
const errors=[];
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.url().startsWith(base) && r.status()>=400)errors.push(r.status()+' '+r.url());});
await page.goto(base+'/?view=desktop');
await page.waitForFunction(()=>document.querySelector('#banner .tip span'));
assert.equal(await page.locator('#banner .list > li').count(),4);
await page.screenshot({path:'research/screenshots/desktop.png',fullPage:true});
await page.locator('#banner .tip span').nth(1).click();
await page.waitForTimeout(1200);
assert.equal(await page.locator('#banner .tip span.cur').textContent(),'2');
await page.locator('#nav > li').filter({hasText:'产品中心'}).hover();
await page.locator('#nav .subnav a').filter({hasText:'永磁变频螺杆机'}).waitFor({state:'visible'});
assert.equal(await page.locator('#nav .subnav a').filter({hasText:'永磁变频螺杆机'}).isVisible(),true);
await page.goto(base+'/product/ycbp/2022-05-03/51.html');
assert.ok((await page.locator('body').textContent()).includes('BMVF永磁变频螺杆空压机'));
assert.equal(await page.locator('img').evaluateAll(imgs=>imgs.filter(i=>!i.complete || i.naturalWidth===0).length),0);
await page.screenshot({path:'research/screenshots/product.png',fullPage:true});
for (const path of ['/news/enterprise/index_2.html','/case/electronic/','/service/after/','/contact/']) {
 const response=await page.goto(base+path);
 assert.equal(response.status(),200,path);
}
await page.goto(base+'/consultation/');
await page.locator('[name=name]').fill('复刻验收');
await page.locator('[name=mycall]').fill('13800000000');
await page.locator('[name=saytext]').fill('本地验收留言，不发送到原站。');
await page.locator('[type=submit]').click();
await page.waitForFunction(()=>document.querySelector('.replica-form-status').textContent.includes('已保存'));
assert.equal(await page.locator('[name=name]').inputValue(),'');
const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const mp=await mobile.newPage();
mp.on('pageerror',e=>errors.push('mobile: '+e.message));
mp.on('response',r=>{if(r.url().startsWith(base) && r.status()>=400)errors.push(r.status()+' '+r.url());});
await mp.goto(base+'/');
await mp.waitForURL(base+'/mobile/');
await mp.waitForFunction(()=>document.querySelector('#banner .tip span'));
assert.ok((await mp.locator('.inav_t').textContent()).includes('产品中心'));
await mp.screenshot({path:'research/screenshots/mobile.png',fullPage:true});
await mp.locator('#nav').click();
assert.ok((await mp.locator('#subNav').getAttribute('class')).includes('subNavShow2'));
await mp.locator('#nav').click();
await mp.locator('#toolbar a').filter({hasText:'微信'}).click();
await mp.waitForTimeout(300);
assert.equal(await mp.locator('#wxnr').isVisible(),true);
await mp.locator('#wxnr i').click();
await mp.goto(base+'/product/ycbp/2022-05-03/51.html');
await mp.waitForURL(base+'/mobile/showinfo-20-51-0.html');
assert.ok((await mp.locator('body').textContent()).includes('BMVF永磁变频螺杆空压机'));
const overflow=await mp.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
assert.equal(overflow,false,'Mobile product detail horizontal overflow');
await mp.goto(base+'/mobile/listinfo-6-0.html');
await mp.locator('[name=name]').fill('手机验收');
await mp.locator('[name=mycall]').fill('13900000000');
await mp.locator('[name=saytext]').fill('手机端本地留言验收。');
await mp.locator('[type=submit]').click();
await mp.waitForFunction(()=>document.querySelector('.replica-form-status').textContent.includes('已保存'));
await mp.goto(base+'/mobile/showinfo-11-9-0.html');
await mp.waitForURL(base+'/news/m/2022-02-23/9.html?view=desktop');
await browser.close();
const relevant=errors;
assert.deepEqual(relevant,[]);
console.log(JSON.stringify({desktop:'passed',mobile:'passed',forms:'both saved',redirects:'passed',screenshots:'research/screenshots',browserErrors:relevant}));
